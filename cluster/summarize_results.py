#!/usr/bin/env python3
"""Write pmb_runs/final/RESULTS.md from the result files linked under final/.

Every number is read from results.csv / the official JSON, never typed in, so
re-running this after a new run updates the summary without transcription.
"""

import glob
import json
import os

import numpy as np
import pandas as pd

from pmb_final import DATASETS, FINAL, final_rows, main_datasets

COLUMNS = {
    "pose/auc_5": ("pose AUC@5 ↑", 1),
    "rays/err_deg": ("ray err ° ↓", 3),
    "sim3/accuracy_median_rel_extent": ("Chamfer acc ↓", 4),
    "sim3/completeness_median_rel_extent": ("Chamfer comp ↓", 4),
    "depth/abs_rel": ("depth abs_rel ↓", 4),
    "metric/scale_abs_rel": ("scale err ↓", 3),
    "gt/covered_ratio": ("GT covered ↑", 3),
    "seconds_per_view": ("s / view ↓", 3),
    "peak_memory_mb": ("peak MB ↓", 0),
}


def load(path):
    df = pd.read_csv(os.path.join(path, "results.csv"))
    return df, df[df.status == "ok"]


def model_table(ok, columns=COLUMNS):
    g = ok.groupby("model")
    rows = []
    for model, part in g:
        row = {"model": model, "sets": len(part)}
        auc = part["pose/auc_5"]
        row[columns["pose/auc_5"][0]] = f"{auc.mean():.1f} ± {auc.std() / len(auc) ** 0.5:.1f}"
        for key, (label, digits) in columns.items():
            if key == "pose/auc_5" or key not in part:
                continue
            value = part[key].mean()
            row[label] = "—" if np.isnan(value) else f"{value:.{digits}f}"
        rows.append(row)
    table = pd.DataFrame(rows)
    order = ok.groupby("model")["pose/auc_5"].mean().sort_values(ascending=False).index
    return table.set_index("model").loc[order].reset_index()


def md(table):
    """Render a DataFrame as a Markdown table (no tabulate dependency)."""
    cols = [str(c) for c in table.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + " --- |" * len(cols)]
    for row in table.itertuples(index=False):
        lines.append("| " + " | ".join("—" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def config_line(path):
    with open(os.path.join(path, "results.json")) as fh:
        cfg = json.load(fh)["config"]
    keys = ("code_revision", "wai_dataset", "image_size", "wai_sets_per_scene", "amp", "mapanything_mask")
    return ", ".join(f"{k}={cfg.get(k)}" for k in keys if k in cfg)


def main():
    out = ["# 3D 点图模型评测 — 详细结果（DETAILS）", "", "简要结果见同目录的 RESULTS.md。", ""]
    out += [
        "All numbers below are generated by `~/pmb_jobs/summarize_results.py` from the",
        "linked result folders; nothing is typed in by hand. ± is the standard error",
        "over sets. Each folder under `final/` links to the raw run (results.csv,",
        "results.json, report.md).",
        "",
    ]

    # Final table at the benchmark's default settings: MapAnything unmasked
    # (as upstream scores it), every other model from the main runs.
    out += ["## 0. Final results at the default settings", "",
            "Upstream protocol (all sets, native resolution, upstream precision), every",
            "pixel scored for every model: MapAnything rows come from",
            "`final/mapanything_nomask/`, the other models from `final/main/`.", ""]
    datasets = main_datasets()
    finals = {}
    chinese = {}
    for name, _, en, cn, n_sets in datasets:
        label = f"{en}, {n_sets} sets"
        main_ok = final_rows(name)
        finals[label] = main_ok
        chinese[label] = f"{en}（{cn}，{n_sets} 组）" if cn else f"{en}（{n_sets} 组）"
        out += [f"### {label}", "", md(model_table(main_ok)), ""]
    ranks = pd.DataFrame({
        label: ok.groupby("model")["pose/auc_5"].mean().rank(ascending=False).astype(int)
        for label, ok in finals.items()
    })
    ranks["mean rank"] = ranks.mean(axis=1)
    ranks = ranks.sort_values("mean rank").reset_index().rename(columns={"index": "model"})
    out += ["### Pose AUC@5 rank on each dataset", "", md(ranks), ""]

    out += ["## 1. Main results (upstream protocol: all sets, native resolution)", "",
            "MapAnything here is with its mask on (the setting these runs used); see",
            "sections 0 and 2 for it unmasked.", ""]
    for name, _, en, _, n_sets in datasets:
        label = f"{en}, {n_sets} sets"
        path = os.path.join(FINAL, "main", name)
        df, ok = load(path)
        out += [f"### {label}", "", f"`final/main/{name}` — {config_line(path)}; "
                f"{len(ok)}/{len(df)} records ok", "", md(model_table(ok)), ""]

    nomask = sorted(glob.glob(os.path.join(FINAL, "mapanything_nomask", "*")))
    if nomask:
        out += ["## 2. MapAnything without its mask (as upstream's benchmark runs it)", "",
                "Section 1 runs MapAnything through `infer()` with its edge/ambiguity mask;",
                "upstream's benchmark calls the model directly and scores every pixel.", ""]
        rows = []
        for path in nomask:
            name = os.path.basename(path)
            df, ok = load(path)
            out += [f"`final/mapanything_nomask/{name}` — {config_line(path)}; "
                    f"{len(ok)}/{len(df)} ok", "", md(model_table(ok)), ""]
            _, masked = load(os.path.join(FINAL, "main", name))
            for model in sorted(ok.model.unique()):
                m = masked[masked.model == model].merge(ok[ok.model == model], on="scene",
                                                        suffixes=("_mask", "_nomask"))
                assert (m.views_digest_mask == m.views_digest_nomask).all()
                for key in ("pose/auc_5", "rays/err_deg", "gt/covered_ratio",
                            "sim3/accuracy_median_rel_extent", "sim3/completeness_median_rel_extent",
                            "depth/abs_rel"):
                    d = m[key + "_nomask"] - m[key + "_mask"]
                    rows.append({"dataset": name.split("_")[0], "model": model, "metric": key,
                                 "mask": round(m[key + "_mask"].mean(), 4),
                                 "no mask": round(m[key + "_nomask"].mean(), 4),
                                 "no mask − mask": round(d.mean(), 4),
                                 "± se": round(d.std() / len(d) ** 0.5, 4)})
        out += ["### Mask vs no mask, same sets", "", md(pd.DataFrame(rows)), ""]

    out += ["## 3. Cross-check against upstream's own benchmark script", ""]
    rows = []
    for official in sorted(glob.glob(os.path.join(FINAL, "official_crosscheck", "*"))):
        model = os.path.basename(official).split("_")[1]
        per_scene = json.load(open(glob.glob(os.path.join(official, "*per_scene_results.json"))[0]))
        eth3d = [d[0] for d in datasets if d[1] == "eth3d"]
        if not eth3d:
            continue
        _, ok = load(os.path.join(FINAL, "main", eth3d[0]))
        ours = ok[ok.model == model]
        off_auc = np.mean([v for m in per_scene.values() for v in m["pose_auc_5"]])
        off_ray = np.mean([v for m in per_scene.values() for v in m["ray_dirs_err_deg"]])
        diff = max(
            abs(np.mean(m["pose_auc_5"]) - ours[ours.wai_scene == s]["pose/auc_5"].mean())
            for s, m in per_scene.items()
        )
        rows.append({
            "model": model, "official AUC@5": f"{off_auc:.4f}", "ours AUC@5": f"{ours['pose/auc_5'].mean():.4f}",
            "official ray err": f"{off_ray:.4f}", "ours ray err": f"{ours['rays/err_deg'].mean():.4f}",
            "max per-scene AUC diff": f"{diff:.4f}",
        })
    out += ["ETH3D, 130 sets, same views. `final/official_crosscheck/`", "", md(pd.DataFrame(rows)), ""]

    out += ["## 4. MASt3R precision: fp32 (upstream) vs bf16 backbone", ""]
    rows = []
    for bf_path in sorted(glob.glob(os.path.join(FINAL, "precision_mast3r_bf16", "*"))):
        bf = os.path.basename(bf_path)
        short = bf.split("_")[0]
        matches = [d for d in datasets if d[0].split("_")[0] == short]
        if not matches:
            continue
        main_name, name = matches[0][0], matches[0][2]
        _, a = load(os.path.join(FINAL, "main", main_name))
        _, b = load(os.path.join(FINAL, "precision_mast3r_bf16", bf))
        m = a[a.model == "mast3r"].merge(b, on="scene", suffixes=("_fp32", "_bf16"))
        assert (m.views_digest_fp32 == m.views_digest_bf16).all()
        for key in ("pose/auc_5", "rays/err_deg", "sim3/accuracy_median_rel_extent", "seconds_per_view", "peak_memory_mb"):
            d = m[key + "_bf16"] - m[key + "_fp32"]
            rows.append({"dataset": name, "metric": key, "fp32": round(m[key + "_fp32"].mean(), 4),
                         "bf16": round(m[key + "_bf16"].mean(), 4), "bf16 − fp32": round(d.mean(), 4),
                         "± se": round(d.std() / len(d) ** 0.5, 4)})
    out += ["`final/precision_mast3r_bf16/`", "", md(pd.DataFrame(rows)), ""]

    out += ["## 5. Earlier: first set per scene only (13 / 5 sets)", "",
            "Kept for the native-vs-448x336 comparison; superseded by section 1 for rankings.", ""]
    rows = []
    for path in sorted(glob.glob(os.path.join(FINAL, "earlier_13sets", "*"))):
        _, ok = load(path)
        s = ok.groupby("model")["pose/auc_5"].mean().round(1)
        s.name = os.path.basename(path)
        rows.append(s)
    out += [md(pd.DataFrame(rows).T.reset_index().rename(columns={"index": "model (pose AUC@5)"})), ""]

    out += ["## 6. Diagnostics: where and how each model fails", "",
            "Default settings (as section 0). Per-scene values are means over that",
            "scene's 10 sets.", ""]
    for label, ok in finals.items():
        g = ok.groupby("model")
        out += [f"### {label}", ""]
        out += ["Harness self-checks - must be ~0 for every model, or that model's",
                "numbers are a conversion bug, not its quality (max over sets):", ""]
        san = g[["sanity/pose_pointmap_rel_err", "sanity/depth_pointmap_rel_err"]].max().round(5)
        out += [md(san.reset_index()), ""]
        for key, title, digits in (("pose/auc_5", "Pose AUC@5 per scene", 0),
                                   ("rays/err_deg", "Ray (intrinsics) error per scene, degrees", 2)):
            piv = ok.pivot_table(index="wai_scene", columns="model", values=key).round(digits)
            out += [f"{title}:", "", md(piv.reset_index()), ""]
        fail = g.apply(lambda x: pd.Series({
            "AUC@5 = 0": (x["pose/auc_5"] == 0).mean(),
            "median rot err > 10°": (x["pose/rot_err_deg_median"] > 10).mean(),
            "median trans dir err > 45°": (x["pose/trans_ang_err_deg_median"] > 45).mean(),
            "consistency@1.03 < 0.3": (x["consistency/inlier_1.03"] < 0.3).mean(),
        })).round(2)
        out += ["Share of sets that failed, by criterion:", "", md(fail.reset_index()), ""]
        metric = ok[ok.model.isin(["mapanything", "mapanything_apache", "mast3r"])]
        sr = metric.groupby("model")["metric/scale_ratio"].describe()[["mean", "25%", "50%", "75%", "min", "max"]].round(2)
        out += ["Metric scale, predicted / GT (1 = correct; models that claim metric scale):", "",
                md(sr.reset_index()), ""]

    out += ["### Camera field of view of the GT (all frames)", "",
            "Horizontal FOV = 2·atan(w / (2·fl_x)) from each frame's scene_meta.json.", ""]
    rows = []
    data_root = "/home/woody/iwfa/iwfa137h/pmb_data"
    for d in [f"{ds}_wai" for _, ds, _, _, _ in datasets]:
        for f in sorted(glob.glob(f"{data_root}/{d}/*/scene_meta.json")):
            meta = json.load(open(f))
            fovs = []
            for fr in meta["frames"]:
                fx, w = fr.get("fl_x", meta.get("fl_x")), fr.get("w", meta.get("w"))
                if fx and w:
                    fovs.append(2 * np.degrees(np.arctan(w / 2 / fx)))
            rows.append({"dataset": d.replace("_wai", ""), "scene": os.path.basename(os.path.dirname(f)),
                         "frames": len(fovs), "median FOV°": round(float(np.median(fovs)), 1),
                         "min": round(min(fovs), 1), "max": round(max(fovs), 1)})
    out += [md(pd.DataFrame(rows)), ""]

    # Hand-written interpretation, kept in its own file so regenerating the
    # tables above never overwrites it.
    findings = os.path.join(os.path.dirname(os.path.abspath(__file__)), "findings.md")
    if os.path.exists(findings):
        out += [open(findings, encoding="utf-8").read()]

    with open(os.path.join(FINAL, "DETAILS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(os.path.join(FINAL, "DETAILS.md"))

    # One-page summary: what was tested, the results, the conclusions.
    here = os.path.dirname(os.path.abspath(__file__))
    names = {"mapanything": "MapAnything", "mapanything_apache": "MapAnything (Apache)",
             "mast3r": "MASt3R", "pi3": "Pi3", "pi3x": "Pi3-X", "vggt": "VGGT", "da3": "DA3"}
    simple = [open(os.path.join(here, "results_intro.md"), encoding="utf-8").read(), "## 结果", ""]
    for label, ok in finals.items():
        g = ok.groupby("model")
        auc = g["pose/auc_5"]
        t = pd.DataFrame({
            "位姿 AUC@5 ↑": [f"{m:.1f} ± {s:.1f}" for m, s in zip(auc.mean(), auc.std() / auc.count() ** 0.5)],
            "内参误差 ° ↓": g["rays/err_deg"].mean().round(2).values,
            "点云误差 ↓": g["sim3/accuracy_median_rel_extent"].mean().round(4).values,
            "深度误差 ↓": g["depth/abs_rel"].mean().round(3).values,
            "尺度误差 ↓": g["metric/scale_abs_rel"].mean().round(2).values,
            "秒 / 张 ↓": g["seconds_per_view"].mean().round(3).values,
        }, index=auc.mean().index)
        t = t.loc[auc.mean().sort_values(ascending=False).index]
        t.insert(0, "排名", range(1, len(t) + 1))
        t.index = [names.get(m, m) for m in t.index]
        cn = chinese[label]
        simple += [f"### {cn}", "", md(t.reset_index().rename(columns={"index": "模型"})), ""]
    simple += ["`± ` 后是标准误差：两个模型的差距小于它，就分不出谁更好。"
               "尺度误差为 — 的模型只输出相对尺度。", "",
               open(os.path.join(here, "results_conclusions.md"), encoding="utf-8").read()]
    with open(os.path.join(FINAL, "RESULTS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(simple))
    print(os.path.join(FINAL, "RESULTS.md"))


if __name__ == "__main__":
    main()
